const ICONS = {
  sun: ["0011100", "0100010", "1000001", "1011101", "1000001", "0100010", "0011100"],
  snow: ["0001000", "0011100", "0001000", "1110111", "0001000", "0011100", "0001000"],
  sound: ["0010000", "0011000", "0011110", "1111111", "0011110", "0011000", "0010000"],
  mute: ["0010001", "0011001", "0011111", "1111111", "0011111", "0011001", "0010001"],
  github: ["0111110", "1000001", "1011101", "1000001", "1010101", "1000001", "0111110"],
  linkedin: ["1111111", "1000001", "1011101", "1000001", "1000001", "1000001", "1111111"],
  mail: ["1111111", "1000001", "1011101", "1100011", "1011101", "1000001", "1111111"],
};

export default function PixelIcon({ name, size = 16 }) {
  const rows = ICONS[name] || ICONS.sun;
  const n = rows[0].length;
  return (
    <svg className="px-icon" width={size} height={size} viewBox={`0 0 ${n} ${rows.length}`} aria-hidden="true">
      {rows.map((row, y) =>
        [...row].map((bit, x) =>
          bit === "1" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" /> : null,
        ),
      )}
    </svg>
  );
}
